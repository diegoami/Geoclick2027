import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {ROOT,PACKAGE,RELEASE_SHA1} from './configure.mjs';
import {assertIsolatedEmulator,parseAvdName,parseInstalledVersion} from './device-safety.mjs';
const serial=process.argv[2]||'emulator-5580';
const sdk=process.env.ANDROID_HOME||process.env.ANDROID_SDK_ROOT||path.join(os.homedir(),'AppData','Local','Android','Sdk');
const adb=path.join(sdk,'platform-tools',process.platform==='win32'?'adb.exe':'adb');
const call=args=>{const r=spawnSync(adb,['-s',serial,...args],{encoding:'utf8',windowsHide:true});if(r.status!==0)throw Error('Android emulator command failed.');return r.stdout.trim()};
const qemu=call(['shell','getprop','ro.kernel.qemu']);
const avdName=parseAvdName(call(['emu','avd','name']));
const existing=call(['shell','dumpsys','package',PACKAGE]);
const version=parseInstalledVersion(existing);
assertIsolatedEmulator({serial,qemu,avdName,versionCode:version});
const out=path.resolve(ROOT,'../../../rendered/firebase-android-proof');
const report=JSON.parse(fs.readFileSync(path.join(out,'build-report.json'),'utf8'));
if(report.packageId!==PACKAGE||report.versionCode!==1||report.releaseSha1!==RELEASE_SHA1||report.emulatorOnly!==true)throw Error('Proof provenance does not match the guarded install.');
const apk=path.join(out,'Geoclick-firebase-auth-proof.apk');
if(createHash('sha256').update(fs.readFileSync(apk)).digest('hex')!==report.apkSha256)throw Error('Proof APK does not match its verified build report.');
call(['install','-r',apk]);
call(['shell','am','start','-n',PACKAGE+'/.MainActivity']);
console.log('PASS: signed auth proof installed on '+serial+' ('+avdName+').');
