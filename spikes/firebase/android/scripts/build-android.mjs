import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createHash} from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { loadEnv } from 'vite';
import { ROOT,PACKAGE,RELEASE_SHA1,configure } from './configure.mjs';
const WIN=process.platform==='win32';
const command=(bin,args,options={})=>spawnSync(bin,args,{cwd:ROOT,encoding:'utf8',shell:WIN&&(/\.(bat|cmd)$/i.test(bin)||bin==='npm'),windowsHide:true,...options});
const step=(bin,args,options={})=>{const result=command(bin,args,{stdio:'inherit',...options});if(result.status!==0)throw Error('Android proof build step failed.');};
const env=loadEnv('production',path.resolve(ROOT,'..'),'VITE_');
let web;try{web=JSON.parse(env.VITE_FIREBASE_CONFIG||'{}')}catch{throw Error('Web Firebase configuration is unreadable.')}
if(env.VITE_FIREBASE_MODE!=='cloud'||!web.projectId||!web.apiKey||!web.appId)throw Error('Configure the dedicated web Firebase test app first.');
const source=process.env.GEOCLICK_FIREBASE_ANDROID_CONFIG_FILE;
if(!source)throw Error('Set GEOCLICK_FIREBASE_ANDROID_CONFIG_FILE to the downloaded Android configuration.');
const metadata=configure(source,web.projectId);
const signing=process.env.GEOCLICK_ANDROID_SIGNING_PROPERTIES;
if(!signing||!fs.existsSync(signing))throw Error('Set GEOCLICK_ANDROID_SIGNING_PROPERTIES to the existing release signing properties.');
const sdk=process.env.ANDROID_HOME||process.env.ANDROID_SDK_ROOT||path.join(os.homedir(),'AppData','Local','Android','Sdk');
if(!process.env.JAVA_HOME)throw Error('Set JAVA_HOME to the compatible JDK used for Android builds.');
step('npm',['run','build'],{env:{...process.env,VITE_ANDROID_FIREBASE_PROJECT:web.projectId}});
step('npm',['run','sync']);
const android=path.join(ROOT,'android');
step(path.join(android,WIN?'gradlew.bat':'gradlew'),['assembleRelease'],{cwd:android,env:{...process.env,ANDROID_HOME:sdk}});
const apk=path.join(android,'app/build/outputs/apk/release/app-release.apk');
if(!fs.existsSync(apk))throw Error('Expected signed release APK is missing.');
const tools=path.join(sdk,'build-tools');
const signer=fs.readdirSync(tools).sort().map(v=>path.join(tools,v,WIN?'apksigner.bat':'apksigner')).filter(fs.existsSync).pop();
if(!signer)throw Error('Android APK signature verifier is missing.');
const signature=command(signer,['verify','--print-certs',apk]);
if(signature.status!==0)throw Error('Proof APK signature verification failed.');
const actual=/certificate SHA-1 digest:\s*([a-fA-F0-9]+)/.exec(signature.stdout)?.[1]?.toLowerCase();
if(actual!==RELEASE_SHA1)throw Error('Proof APK does not match the registered release certificate.');
const out=path.resolve(ROOT,'../../../rendered/firebase-android-proof');fs.mkdirSync(out,{recursive:true});
fs.copyFileSync(apk,path.join(out,'Geoclick-firebase-auth-proof.apk'));
fs.writeFileSync(path.join(out,'build-report.json'),JSON.stringify({...metadata,versionCode:1,releaseSha1:actual,apkSha256:createHash('sha256').update(fs.readFileSync(apk)).digest('hex'),emulatorOnly:true,realNativeGoogleVerified:false},null,2)+'\n');
console.log('PASS: signed Android proof built for '+PACKAGE+'; install only on an isolated emulator.');
